"""REGRESSION GATE for the run-22 .data change to rel_carve.py.

Five landed carves in the tree (mini_golf, option, test_mode, sel_ngc,
mini_pilot) were generated by the PRE-run-22 tool.  If the rewrite changes what
a .rodata-only carve emits by so much as a byte, every one of them is at risk
the next time anybody re-runs rel_carve -- and the failure mode is a non-golden
hash with nothing in the diff to point at.

So: run the OLD tool and the NEW tool over the same pristine blob with the same
.rodata-only arguments, in two identical throwaway trees, and require the
emitted asm/*.s AND the Makefile SOURCES block to be byte-identical.

  python regress_rodata.py
"""
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MAIN = os.path.dirname(HERE)
NEW = os.path.join(HERE, 'rel_carve.py')

# The BASELINE is whatever rel_carve.py looked like at a given git rev (default:
# the commit that landed .data support).  Extracting it from git rather than
# hard-coding a second path means this gate keeps working after the tool lands,
# and answers the only question that matters: "does my change still emit
# byte-identical .rodata carves?"
BASE_REV = os.environ.get('CARVE_BASE_REV', '984524c')
OLD = os.path.join(HERE, '_carve_baseline.py')

# CARVE_BASE_FILE names the baseline directly, bypassing git.  A warm copy's
# HEAD is run-9 era, so `git show 984524c:` does NOT resolve there and this gate
# was unusable in every one of them -- run 23 hit that in four modules
# independently (mini_fight, mini_golf, mini_billiards, mini_race), and three of
# them had to hand-copy the gate to get a baseline in.  Any file path works;
# _orch_run<N>/rel_carve.PRE_RUN<N>.py is the natural one.
_bf = os.environ.get('CARVE_BASE_FILE')
if _bf:
    if not os.path.exists(_bf):
        sys.exit('CARVE_BASE_FILE does not exist: %s' % _bf)
    open(OLD, 'wb').write(open(_bf, 'rb').read())
else:
    _blob = subprocess.run(['git', 'show', '%s:tools/rel_carve.py' % BASE_REV],
                           cwd=MAIN, capture_output=True)
    if _blob.returncode:
        sys.exit('cannot read tools/rel_carve.py at %s -- pass CARVE_BASE_REV=<rev>,\n'
                 '  or CARVE_BASE_FILE=<path> if you are in a warm copy (its HEAD\n'
                 '  is run-9 era and will not resolve any recent rev).'
                 % BASE_REV)
    open(OLD, 'wb').write(_blob.stdout)

# (module, [carve args])  -- .rodata only, the shapes the landed carves used.
# Hand cases first, then one auto-derived pair per module (below) so the gate
# covers all nine, not just the one it was written against.
CASES = [
    ('mini_bowling', ['--hole', 'lbl_00010D60:8', '--into', 'src/mini_bowling_20.c',
                      '--force']),
    ('mini_bowling', ['--hole', 'lbl_00010CC0', '--into', 'src/mini_bowling_4b.c']),
    ('mini_bowling', ['--hole-range', 'lbl_00010EE0:lbl_00010EE8',
                      '--into', 'src/mini_bowling_11.c']),
    ('mini_bowling', ['--hole', 'lbl_00010CC0', '--into', 'src/mini_bowling_4b.c',
                      '--hole', 'lbl_00010EE0', '--into', 'src/mini_bowling_11.c']),
]

MODULES = ['mini_bowling', 'mini_race', 'mini_fight', 'mini_pilot', 'mini_golf',
           'mini_billiards', 'sel_ngc', 'option', 'test_mode']


def autocases():
    """For each module, carve the first two <=8-byte rodata labels that have a
    C owner -- one alone, then both together (which exercises the multi-segment
    SOURCES interleave)."""
    out = []
    for mod in MODULES:
        d = build(mod, 'probe')
        shutil.copy(NEW, os.path.join(d, 'tools', 'rel_carve.py'))
        r = subprocess.run([sys.executable, 'tools/rel_carve.py', mod, '--list',
                            '--from', 'worktree'], cwd=d, capture_output=True,
                           text=True)
        picks = []
        for line in r.stdout.split('\n'):
            f = line.split()
            if len(f) >= 5 and f[0].startswith('lbl_') and f[4].startswith('src/'):
                try:
                    nb = int(f[2])
                except ValueError:
                    continue
                if 0 < nb <= 8 and f[4] not in [p[1] for p in picks]:
                    picks.append((f[0], f[4]))
            if len(picks) == 2:
                break
        shutil.rmtree(d)
        if picks:
            out.append((mod, ['--hole', picks[0][0], '--into', picks[0][1]]))
        if len(picks) == 2:
            args = []
            for lbl, own in picks:
                args += ['--hole', lbl, '--into', own]
            out.append((mod, args))
    return out


def build(mod, tag):
    d = os.path.join(HERE, 'rg_%s' % tag)
    subprocess.run([sys.executable,
                    os.path.join(HERE, 'rel_blob_reassemble.py'), mod, d],
                   check=True, capture_output=True)
    return d


def run(tool, tree, mod, args):
    shutil.copy(tool, os.path.join(tree, 'tools', 'rel_carve.py'))
    return subprocess.run(
        [sys.executable, 'tools/rel_carve.py', mod, '--from', 'worktree'] + args,
        cwd=tree, capture_output=True, text=True)


def snapshot(tree, mod):
    out = {}
    for f in sorted(os.listdir(os.path.join(tree, 'asm'))):
        if f.endswith('.s'):
            out[f] = open(os.path.join(tree, 'asm', f), 'rb').read()
    out['Makefile'] = open(os.path.join(tree, 'Makefile'), 'rb').read()
    return out


CASES += autocases()

bad = 0
for n, (mod, args) in enumerate(CASES):
    a, b = build(mod, 'old'), build(mod, 'new')
    ra, rb = run(OLD, a, mod, args), run(NEW, b, mod, args)
    sa, sb = snapshot(a, mod), snapshot(b, mod)
    same_files = sorted(sa) == sorted(sb)
    diffs = [f for f in sa if f in sb and sa[f] != sb[f]]
    ok = same_files and not diffs and (ra.returncode == rb.returncode)
    print('case %d  %-14s %-58s %s'
          % (n, mod, ' '.join(args)[:58], 'IDENTICAL' if ok else 'DIFFERS'))
    if not ok:
        bad += 1
        print('   old rc=%d new rc=%d' % (ra.returncode, rb.returncode))
        if not same_files:
            print('   old files: %s\n   new files: %s' % (sorted(sa), sorted(sb)))
        for f in diffs:
            oldl = sa[f].decode('latin-1').split('\n')
            newl = sb[f].decode('latin-1').split('\n')
            print('   %s: %d vs %d lines' % (f, len(oldl), len(newl)))
            for i, (x, y) in enumerate(zip(oldl, newl)):
                if x != y:
                    print('     first diff line %d:\n       old %r\n       new %r'
                          % (i + 1, x, y))
                    break
        if ra.returncode or rb.returncode:
            print('   old stderr: %s' % ra.stderr.strip()[:300])
            print('   new stderr: %s' % rb.stderr.strip()[:300])
    shutil.rmtree(a)
    shutil.rmtree(b)

os.remove(OLD)                       # do not leave a baseline copy in tools/
print('\n%d/%d cases byte-identical (baseline %s)'
      % (len(CASES) - bad, len(CASES), BASE_REV))
sys.exit(1 if bad else 0)
